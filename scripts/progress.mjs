// Progress towards 0.1.0: reads docs/v1-icons.json, checks which icons are drawn (icons/core,
// icons/thai) and writes docs/v1-icons.md.
//   npm run progress
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

/**
 * @typedef {{ name: string, batch: number, used?: string[], note?: string }} PlanIcon
 * @typedef {PlanIcon & { group: string, thai: boolean, drawn: boolean}} PlanRow
 * @returns {{ plan: { batches: Record<string, string>, groups: { title: string, thai?: boolean, icons: PlanIcon[] }[] }, rows: PlanRow[] }}
 */
export function loadPlan() {
  const plan = JSON.parse(readFileSync('docs/v1-icons.json', 'utf8'));
  const rows = plan.groups.flatMap((g) =>
    g.icons.map((i) => {
      const dir = g.thai ? 'icons/thai' : 'icons/core';
      return {
        ...i,
        group: g.title,
        thai: Boolean(g.thai),
        drawn: existsSync(`${dir}/${i.name}.svg`),
      };
    }),
  );
  return { plan, rows };
}

function main() {
  const { plan, rows } = loadPlan();
  const done = rows.filter((r) => r.drawn).length;
  const lines = [
    '# thira-icons 0.1.0 icon list',
    '',
    `Generated by \`npm run progress\` from [v1-icons.json](v1-icons.json) — edit the JSON, not this file.`,
    '',
    `**${done} / ${rows.length} drawn.**`,
    '',
    '| Batch | Scope | Drawn |',
    '| --- | --- | --- |',
    ...Object.entries(plan.batches).map(([b, scope]) => {
      const inBatch = rows.filter((r) => String(r.batch) === b);
      return `| ${b} | ${scope} | ${inBatch.filter((r) => r.drawn).length} / ${inBatch.length} |`;
    }),
    '',
  ];
  for (const g of plan.groups) {
    const groupRows = rows.filter((r) => r.group === g.title);
    lines.push(`## ${g.title} (${groupRows.filter((r) => r.drawn).length} / ${groupRows.length})`, '');
    lines.push('| Icon | Batch | Status | Used by / note |', '| --- | --- | --- | --- |');
    for (const r of groupRows) {
      const status = r.drawn ? '✅ drawn' : '⬜ to draw';
      const note = [...(r.used ?? []), r.note].filter(Boolean).join('; ');
      lines.push(`| \`${r.name}\` | ${r.batch} | ${status} | ${note} |`);
    }
    lines.push('');
  }
  writeFileSync('docs/v1-icons.md', lines.join('\n'));
  console.log(`${done} / ${rows.length} drawn → docs/v1-icons.md`);
}

if (process.argv[1]?.replace(/\\/g, '/').endsWith('scripts/progress.mjs')) main();
